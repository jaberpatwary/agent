// One-off generator: reads saved Daily Star category pages and writes the
// portal's block templates (web/templates/public/blocks.html) and the block
// list per category (internal/handler/blocks_gen.go).
//
//	go run ./cmd/_gen <dir with the saved pages>
//
// The pages are fetched with curl from bangla.thedailystar.net (see pages below).
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/PuerkitoBio/goquery"
	"golang.org/x/net/html"
)

type page struct{ file, category string }

var pages = []page{
	{"news_bangladesh.html", "bangladesh"},
	{"international.html", "international"},
	{"opinion_views.html", "opinion"},
	{"sports.html", "sports"},
	{"business.html", "business"},
	{"entertainment.html", "entertainment"},
	{"life-living.html", "lifestyle"},
	{"tech-startup.html", "technology"},
}

var layoutRe = regexp.MustCompile(`\bnews-section-layout-(\d+)\b`)

func hasClass(s *goquery.Selection, c string) bool {
	return s.HasClass(c)
}

func attr(s *goquery.Selection, name string) string {
	v, _ := s.Attr(name)
	return strings.Join(strings.Fields(v), " ")
}

func tick(s string) string { return "`" + s + "`" }

type gen struct {
	n   int // next story index in the block
	out strings.Builder
}

// card writes the template call for one card element.
func (g *gen) card(c *goquery.Selection) {
	idx := g.n
	g.n++
	col := c.Find(".card-image-col").First()
	img := c.Find(".card-image").First()
	content := c.Find(".card-content").First()
	var order []string
	titleTag, titleCls, introCls := "h5", "card-title ", ""
	content.Children().Each(func(_ int, ch *goquery.Selection) {
		name := goquery.NodeName(ch)
		switch {
		case len(name) == 2 && name[0] == 'h' && name[1] >= '1' && name[1] <= '6':
			titleTag, titleCls = name, attr(ch, "class")+" "
			order = append(order, "title")
		case hasClass(ch, "card-intro"):
			introCls = attr(ch, "class")
			order = append(order, "intro")
		case hasClass(ch, "card-info"):
			order = append(order, "info")
		}
	})
	// The intro of some cards sits beside the content, not inside it.
	if introCls == "" {
		if in := c.Find(".card-intro").First(); in.Length() > 0 {
			introCls = attr(in, "class")
			order = append(order, "intro")
		}
	}
	if !contains(order, "info") {
		if c.Find(".card-info").Length() > 0 {
			order = append(order, "info")
		}
	}
	fmt.Fprintf(&g.out, "{{ with at .S %d }}{{ template \"dscard\" (dict \"A\" . \"Card\" %s \"HasImg\" %v \"Col\" %s \"Img\" %s \"Content\" %s \"Tag\" %s \"TitleCls\" %s \"IntroCls\" %s \"Order\" %s) }}{{ end }}\n",
		idx, tick(attr(c, "class")), img.Length() > 0, tick(attr(col, "class")), tick(attr(img, "class")),
		tick(attr(content, "class")), tick(titleTag), tick(strings.TrimRight(titleCls, " ")+" "), tick(introCls), tick(strings.Join(order, " ")))
}

func contains(l []string, s string) bool {
	for _, v := range l {
		if v == s {
			return true
		}
	}
	return false
}

// walk copies the container structure and replaces every card.
func (g *gen) walk(s *goquery.Selection) {
	s.Children().Each(func(_ int, ch *goquery.Selection) {
		if goquery.NodeName(ch) != "div" || hasClass(ch, "section-title-wrapper") {
			return
		}
		if hasClass(ch, "card") {
			g.card(ch)
			return
		}
		if ch.Find(".card").Length() == 0 {
			return // ads and other empty containers
		}
		fmt.Fprintf(&g.out, "<div class=%q>\n", attr(ch, "class"))
		g.walk(ch)
		g.out.WriteString("</div>\n")
	})
}

func main() {
	dir := os.Args[1]
	var tpl, specs, dispatch strings.Builder
	specs.WriteString("// Code generated by cmd/_gen from The Daily Star's category pages; DO NOT EDIT.\n\npackage handler\n\n// categoryBlocks lists the blocks of each category page in order: the\n// template, the sub-section title and how many stories it shows.\nvar categoryBlocks = map[string][]BlockSpec{\n")
	for _, p := range pages {
		f, err := os.Open(filepath.Join(dir, p.file))
		if err != nil {
			panic(err)
		}
		doc, err := goquery.NewDocumentFromReader(f)
		f.Close()
		if err != nil {
			panic(err)
		}
		fmt.Fprintf(&specs, "\t%q: {\n", p.category)
		i := 0
		doc.Find("div[class*='news-section-layout-']").Each(func(_ int, blk *goquery.Selection) {
			m := layoutRe.FindStringSubmatch(attr(blk, "class"))
			if m == nil || blk.Closest("div[class*='news-section-layout-']").Get(0) != blk.Get(0) {
				return
			}
			title := strings.Join(strings.Fields(blk.Find(".section-title").First().Text()), " ")
			if strings.Contains(title, "মাল্টিমি") {
				return // videos: the portal has none for a category
			}
			g := &gen{}
			fmt.Fprintf(&g.out, "<div class=%q>\n", attr(blk, "class"))
			// The title row is written once, here, from the block's data.
			g.walkRoot(blk, title != "")
			g.out.WriteString("</div>\n")
			key := fmt.Sprintf("blk_%s_%d", p.category, i)
			fmt.Fprintf(&tpl, "{{ define %q }}\n%s{{ end }}\n\n", key, g.out.String())
			if dispatch.Len() > 0 {
				dispatch.WriteString("{{ else if ")
			} else {
				dispatch.WriteString("{{ if ")
			}
			fmt.Fprintf(&dispatch, "eq .Key %q }}{{ template %q . }}\n", key, key)
			fmt.Fprintf(&specs, "\t\t{Key: %q, Title: %q, Layout: %s, Cards: %d},\n", key, title, m[1], g.n)
			i++
		})
		specs.WriteString("\t},\n")
	}
	specs.WriteString("}\n")
	head := "{{/* Generated by cmd/_gen from The Daily Star's category pages: do not edit by hand. Each block takes S (stories), Title and Href. */}}\n"
	body := head + tpl.String() + "{{ define \"cat_block\" }}" + dispatch.String() + "{{ end }}{{ end }}\n"
	must(os.WriteFile("web/templates/public/blocks.html", []byte(body), 0o644))
	must(os.WriteFile("internal/handler/blocks_gen.go", []byte(specs.String()), 0o644))
}

// walkRoot walks a block's root, writing the title row where the original has it.
func (g *gen) walkRoot(root *goquery.Selection, hasTitle bool) {
	root.Children().Each(func(_ int, ch *goquery.Selection) {
		if goquery.NodeName(ch) != "div" {
			return
		}
		if ch.Find(".card").Length() == 0 && ch.Find(".section-title").Length() == 0 {
			return
		}
		fmt.Fprintf(&g.out, "<div class=%q>\n", attr(ch, "class"))
		g.walkWithTitle(ch, hasTitle)
		g.out.WriteString("</div>\n")
	})
}

func (g *gen) walkWithTitle(s *goquery.Selection, hasTitle bool) {
	s.Children().Each(func(_ int, ch *goquery.Selection) {
		if goquery.NodeName(ch) != "div" {
			return
		}
		if hasClass(ch, "section-title-wrapper") {
			if hasTitle {
				g.out.WriteString("{{ if .Title }}<div class=\"section-title-wrapper\"><h2 class=\"section-title\"><a href=\"{{ .Href }}\"> {{ .Title }} </a></h2></div>{{ end }}\n")
			}
			return
		}
		if hasClass(ch, "card") {
			g.card(ch)
			return
		}
		if ch.Find(".card").Length() == 0 {
			return
		}
		fmt.Fprintf(&g.out, "<div class=%q>\n", attr(ch, "class"))
		g.walkWithTitle(ch, hasTitle)
		g.out.WriteString("</div>\n")
	})
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}

